    path('employer/create/', JobCreateView.as_view(), name='job_create'),
    path('employer/<int:pk>/edit/', JobUpdateView.as_view(), name='job_edit'),
    path('employer/<int:pk>/delete/', JobDeleteView.as_view(), name='job_delete'),
